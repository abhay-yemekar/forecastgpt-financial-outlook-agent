import shutil
import subprocess
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parent.parent / "scripts" / "check-attribution.sh"

pytestmark = pytest.mark.skipif(shutil.which("bash") is None, reason="needs bash")


def _check(text: str) -> int:
    return subprocess.run(["bash", str(SCRIPT)], input=text, text=True, capture_output=True).returncode


@pytest.mark.parametrize(
    "text",
    [
        "fix(fetch): one scrape per job\n\nCloses #27",
        "Reports are generated with Gemini via the OpenAI-compatible endpoint.",
        "Anthropic is one of the supported LLM providers.",
        "Co-authored-by: Jane Doe <jane@example.com>",
    ],
)
def test_clean_text_passes(text):
    assert _check(text) == 0


@pytest.mark.parametrize(
    "text",
    [
        "feat: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>",
        "co-authored-by: Copilot <copilot@github.com>",
        "Body\n\nGenerated with [Claude Code](https://claude.com/claude-code)",
        "generated by ChatGPT",
    ],
)
def test_ai_attribution_fails(text):
    assert _check(text) == 1
